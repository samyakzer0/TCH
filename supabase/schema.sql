-- Enable UUID extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. MENU ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.menu_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    price NUMERIC(10, 2) NOT NULL,
    category TEXT NOT NULL,
    image_url TEXT,
    is_available BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. ORDERS TABLE
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    customer_name TEXT,
    customer_phone TEXT,
    customer_email TEXT,
    order_type TEXT NOT NULL CHECK (order_type IN ('dine-in', 'takeaway')),
    table_number TEXT,
    status TEXT NOT NULL DEFAULT 'received' CHECK (status IN ('received', 'preparing', 'ready', 'completed', 'cancelled')),
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    special_instructions TEXT,
    estimated_completion_time TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. ORDER ITEMS TABLE
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    menu_item_id BIGINT REFERENCES public.menu_items(id) ON DELETE SET NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    price NUMERIC(10, 2) NOT NULL,
    customizations JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. FEEDBACK TABLE
CREATE TABLE IF NOT EXISTS public.feedback (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    food_quality_rating INTEGER CHECK (food_quality_rating >= 1 AND food_quality_rating <= 5),
    service_speed_rating INTEGER CHECK (service_speed_rating >= 1 AND service_speed_rating <= 5),
    value_rating INTEGER CHECK (value_rating >= 1 AND value_rating <= 5),
    overall_rating INTEGER CHECK (overall_rating >= 1 AND overall_rating <= 5),
    comments TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. SPECIAL OFFERS TABLE
CREATE TABLE IF NOT EXISTS public.special_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. ADMIN USERS TABLE
CREATE TABLE IF NOT EXISTS public.admin_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    password TEXT, -- optional password (nullable for Google Auth users)
    role TEXT NOT NULL DEFAULT 'staff' CHECK (role IN ('owner', 'staff')),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- =============================================================================
-- AUTOMATIC SCHEMA COMPATIBILITY UPGRADES
-- (Ensures pre-existing SQLite-style integer columns are converted to boolean)
-- =============================================================================
DO $$ 
BEGIN 
    -- 1. Convert menu_items.is_available from integer to boolean if needed
    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' 
          AND table_name = 'menu_items' 
          AND column_name = 'is_available'
          AND data_type IN ('integer', 'smallint', 'bigint', 'numeric')
    ) THEN 
        ALTER TABLE public.menu_items ALTER COLUMN is_available DROP DEFAULT;
        ALTER TABLE public.menu_items 
            ALTER COLUMN is_available TYPE BOOLEAN 
            USING (CASE WHEN is_available = 1 THEN true ELSE false END);
        ALTER TABLE public.menu_items ALTER COLUMN is_available SET DEFAULT true;
    END IF;

    -- 2. Convert special_offers.is_active from integer to boolean if needed
    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' 
          AND table_name = 'special_offers' 
          AND column_name = 'is_active'
          AND data_type IN ('integer', 'smallint', 'bigint', 'numeric')
    ) THEN 
        ALTER TABLE public.special_offers ALTER COLUMN is_active DROP DEFAULT;
        ALTER TABLE public.special_offers 
            ALTER COLUMN is_active TYPE BOOLEAN 
            USING (CASE WHEN is_active = 1 THEN true ELSE false END);
        ALTER TABLE public.special_offers ALTER COLUMN is_active SET DEFAULT true;
    END IF;

    -- 3. Ensure password in admin_users is nullable if table existed with NOT NULL
    IF EXISTS (
        SELECT 1 FROM information_schema.columns 
        WHERE table_schema = 'public' 
          AND table_name = 'admin_users' 
          AND column_name = 'password'
    ) THEN 
        ALTER TABLE public.admin_users ALTER COLUMN password DROP NOT NULL;
    ELSE
        ALTER TABLE public.admin_users ADD COLUMN IF NOT EXISTS password TEXT;
    END IF;
END $$;

-- =============================================================================
-- INDEXES & CONSTRAINTS
-- =============================================================================
CREATE UNIQUE INDEX IF NOT EXISTS idx_menu_items_name ON public.menu_items(name);
CREATE UNIQUE INDEX IF NOT EXISTS idx_special_offers_title ON public.special_offers(title);
CREATE INDEX IF NOT EXISTS idx_orders_order_number ON public.orders(order_number);
CREATE INDEX IF NOT EXISTS idx_orders_phone ON public.orders(customer_phone);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_created_at ON public.orders(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_order_items_order_id ON public.order_items(order_id);
CREATE INDEX IF NOT EXISTS idx_feedback_order_id ON public.feedback(order_id);

-- =============================================================================
-- AUTO UPDATE TIMESTAMP TRIGGER
-- =============================================================================
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_menu_items_updated_at ON public.menu_items;
CREATE TRIGGER trigger_menu_items_updated_at
    BEFORE UPDATE ON public.menu_items
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS trigger_orders_updated_at ON public.orders;
CREATE TRIGGER trigger_orders_updated_at
    BEFORE UPDATE ON public.orders
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS trigger_special_offers_updated_at ON public.special_offers;
CREATE TRIGGER trigger_special_offers_updated_at
    BEFORE UPDATE ON public.special_offers
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_updated_at();

